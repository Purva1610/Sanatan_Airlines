const pillarIcons = [HeartHandshake, Globe2, MessagesSquare, ShieldCheck];
const valueIcons = [HeartHandshake, BadgeCheck, ShieldCheck];
const stepIcons = [Send, MessagesSquare, ClipboardCheck, PlaneTakeoff];

export default function WhyChooseSanatan() {
  const [language, setLanguage] = useState('en');

  useEffect(() => {
    try {
      const savedLanguage = window.localStorage.getItem('sa_lang');
      if (LANGUAGES.some(({ code }) => code === savedLanguage)) setLanguage(savedLanguage);
    } catch {
      // The selected language remains available for this page even when storage is disabled.
    }
  }, []);

  const content = translations[language] || translations.en;
  const languageMeta = LANGUAGES.find(({ code }) => code === language) || LANGUAGES[0];

  const updateLanguage = (event) => {
    const nextLanguage = event.target.value;
    setLanguage(nextLanguage);
    try {
      window.localStorage.setItem('sa_lang', nextLanguage);
    } catch {
      // The selected language remains available for this page even when storage is disabled.
    }
  };

  return (
    <div
      className="scs-sections"
      lang={language}
      dir={languageMeta.dir}
      style={{ fontFamily: SCRIPT_FONTS[languageMeta.script] || SCRIPT_FONTS.latin }}
    >
      <section className="scs-why" id="why-sanatan" aria-labelledby="scs-why-title">
        <div className="scs-container">
          <div className="scs-heading-row">
            <div className="scs-heading-copy">
              <span className="scs-eyebrow">{content.eyebrow}</span>
              <h2 id="scs-why-title">{content.whyTitle}</h2>
              <p>{content.whyIntro}</p>
            </div>
            <label className="scs-language-control">
              <Globe2 size={16} aria-hidden="true" />
              <span>{content.language}</span>
              <select value={language} onChange={updateLanguage}>
                {LANGUAGES.map(({ code, nativeLabel }) => <option value={code} key={code}>{nativeLabel}</option>)}
              </select>
            </label>
          </div>

          <div className="scs-pillar-grid">
            {content.pillars.map(([title, description], index) => {
              const Icon = pillarIcons[index];
              return (
                <article className="scs-pillar-card" key={title}>
                  <span className="scs-icon"><Icon size={21} strokeWidth={1.6} aria-hidden="true" /></span>
                  <span className="scs-card-index">{String(index + 1).padStart(2, '0')}</span>
                  <h3>{title}</h3>
                  <p>{description}</p>
                </article>
              );
            })}
          </div>

          <div className="scs-values">
            <div className="scs-values-heading">
              <span className="scs-eyebrow">{content.valuesIntro}</span>
              <h3>{content.valuesTitle}</h3>
            </div>
            <div className="scs-values-grid">
              {content.values.map(([name, meaning, description], index) => {
                const Icon = valueIcons[index];
                return (
                  <article className="scs-value-card" key={name}>
                    <Icon size={19} strokeWidth={1.6} aria-hidden="true" />
                    <div><h4>{name}</h4><strong>{meaning}</strong><p>{description}</p></div>
                  </article>
                );
              })}
            </div>
          </div>
        </div>
      </section>

      <section className="scs-process" id="how-it-works" aria-labelledby="scs-process-title">
        <div className="scs-container">
          <div className="scs-process-heading">
            <span className="scs-eyebrow">{content.processEyebrow}</span>
            <h2 id="scs-process-title">{content.processTitle}</h2>
            <p>{content.processIntro}</p>
          </div>
          <ol className="scs-step-grid">
            {content.steps.map(([title, description], index) => {
              const Icon = stepIcons[index];
              return (
                <li className="scs-step-card" key={title}>
                  <div className="scs-step-top">
                    <span className="scs-step-number">{String(index + 1).padStart(2, '0')}</span>
                    <span className="scs-step-icon"><Icon size={19} strokeWidth={1.6} aria-hidden="true" /></span>
                  </div>
                  <h3>{title}</h3>
                  <p>{description}</p>
                </li>
              );
            })}
          </ol>
        </div>
      </section>
    </div>
  );
}
